#!/usr/bin/env python3
"""Writes real RTP packets, made by ffmpeg's own packetizer, as a Kotlin test fixture.

usage: rtp_vectors.py <output .kt file> <kotlin package>

For each codec (H.264 with libx264, H.265 with libx265) it encodes a few tiny frames, lets ffmpeg's RTP muxer packetize that elementary stream with a small
packet size (so single NAL units, aggregation packets and fragments all occur), captures the packets, and records them together with the encoder's own NAL
units (read from the elementary stream, not from our code) and ffmpeg's SDP. The Kotlin tests then require that Patchbay's depacketizers turn the packets back
into exactly those NAL units. Needs ffmpeg with libx264 and libx265; run it by hand when the fixture must be regenerated.
"""
import os, socket, subprocess, sys, tempfile, re


def nals(data):
    starts = [m.start() for m in re.finditer(b"\x00\x00\x01", data)]
    out = []
    for k, s in enumerate(starts):
        nal = data[s + 3:starts[k + 1] if k + 1 < len(starts) else len(data)]
        while nal.endswith(b"\x00"):
            nal = nal[:-1]
        out.append(nal)
    return out


def capture(codec, work):
    raw, enc = ("h264", ["-c:v", "libx264", "-preset", "ultrafast", "-x264-params", "slices=2:keyint=3:log-level=error"]) if codec == "h264" else \
               ("hevc", ["-c:v", "libx265", "-preset", "ultrafast", "-x265-params", "keyint=3:log-level=error:repeat-headers=1"])
    ref = os.path.join(work, "ref." + codec)
    sdp_path = os.path.join(work, codec + ".sdp")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", "testsrc2=size=64x64:rate=5", "-frames:v", "6"] + enc + ["-f", raw, ref], check=True)
    udp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    udp.bind(("127.0.0.1", 0))
    udp.settimeout(0.5)
    port = udp.getsockname()[1]
    p = subprocess.Popen(["ffmpeg", "-y", "-loglevel", "error", "-re", "-f", raw, "-i", ref, "-c", "copy", "-f", "rtp", "-sdp_file", sdp_path,
                          "rtp://127.0.0.1:%d?pkt_size=300" % port], stderr=subprocess.PIPE, text=True)
    packets, idle = [], 0
    while True:
        try:
            packets.append(udp.recvfrom(65535)[0])
            idle = 0
        except socket.timeout:
            idle += 1
            if p.poll() is not None and idle >= 2:
                break
    if p.returncode != 0 or not packets:
        sys.exit("ffmpeg failed: " + p.stderr.read())
    return packets, nals(open(ref, "rb").read()), open(sdp_path).read()


def kotlin_list(items):
    return "listOf(\n" + "".join('        "%s",\n' % i.hex() for i in items) + "    )"


def main():
    out_path, package = sys.argv[1], sys.argv[2]
    with tempfile.TemporaryDirectory() as work:
        parts = []
        for codec, name in (("h264", "H264"), ("h265", "H265")):
            packets, ref_nals, sdp = capture(codec, work)
            parts.append("    /** %s: %d RTP packets from ffmpeg's packetizer (packet size 300), the encoder's %d NAL units, and ffmpeg's SDP. */\n" % (name, len(packets), len(ref_nals)))
            parts.append("    val %s_PACKETS: List<String> = %s\n\n" % (name, kotlin_list(packets)))
            parts.append("    val %s_NALS: List<String> = %s\n\n" % (name, kotlin_list(ref_nals)))
            parts.append('    val %s_SDP: String = """%s"""\n\n' % (name, sdp.replace("\r\n", "\n").replace("$", "${'$'}")))
    with open(out_path, "w") as f:
        f.write("package %s\n\n" % package)
        f.write("// Generated by tools/interop/rtp_vectors.py from ffmpeg's own RTP packetizer. Do not edit by hand.\n")
        f.write("internal object RealRtpVectors {\n" + "".join(parts).rstrip() + "\n}\n")
    print("wrote", out_path)


main()
